def _handler(s: Shape, p: dict) -> str:
    op, args = p["op"], f"{s.name}Args"
    if op in EVENT_OPS:
        return f"HookEvent<{args}>"
    if op in ("fold-add", "fold-mul", "fold-set"):
        return f"HookFold<{args}, {s.vtype}>"
    if op == "fold-cap":
        return f"HookCap<{args}, {s.vtype}>"
    if op == "try":
        if not s.value:
            return f"HookTryInPlace<{args}>"
        if "out-not-null" in p.get("also", []):
            return f"HookTryOrNull<{args}, {s.vtype}>"
        return f"HookTry<{args}, {s.vtype}>"
    if op.startswith("predicate"):
        return f"HookPredicate<{args}>"
    return f"HookMutate<{args}>"


def _event_body(s: Shape, i: int, p: dict, ctx_mode: str) -> list[str]:
    hook = f"HookId.{p['hook']}"
    out = []
    if ctx_mode in ("passed", "passed-unpushed", "caller-hook"):
        ctx = s.arg("ChoiceCtx")
    elif ctx_mode == "per-listener":
        out.append(f"var ctx = rt.NewHookContext({disp_id(s.name)}, e.Who);")
        ctx = "ctx"
    else:
        ctx = "null"
    push = ctx_mode in PUSH
    if push:
        out.append(f"{ctx}.PushModel(e.Who);")
    out.append(f"var step = e.Fn(e.Who, in a, {ctx});")
    site = f"new PauseSite({disp_id(s.name)}, {hook}, {i}, l.Index, e.Who, ContextMode.{CTX[ctx_mode]}, {ctx})"
    if s.stops:
        # The game awaits the listener's task: the later listeners wait for the answer (pushed until Resume).
        out += ["if (step.IsPaused)", "{", f"    var site = {site};", "    rt.OnPaused(in site, step);",
                "    return HookStatus.Paused(in site, step, l);", "}"]
    else:
        out.append(f"if (step.IsPaused) rt.OnPaused({site}, step);")
    if push:
        out.append(f"{ctx}.PopModel(e.Who);")
    return out


ADD = "(ch ??= new()).Add(e.Who);"


def _pass_body(s: Shape, i: int, p: dict) -> list[str]:
    op, changed, v = p["op"], p["changed"], s.vtype
    if op == "event":
        return _event_body(s, i, p, s.d["context"])
    if op == "filter-set":
        return [f"if (!HookRuntime.Contains({s.arg('ListenerSet')}, e.Who)) continue;"] + _event_body(s, i, p, "none")
    if op == "preventer-only":
        return [f"if (e.Who != {s.arg('ListenerRef')}) continue;"] + _event_body(s, i, p, "none") + ["break;"]
    if op == "fold-add":
        return [f"{v} d = e.Fn(e.Who, in a, v);", "v += d;"] + ([f"if (d != 0m) {ADD}"] if changed != "none" else [])
    if op == "fold-mul":
        return [f"{v} f = e.Fn(e.Who, in a, v);", "v *= f;"] + ([f"if (f != 1m) {ADD}"] if changed != "none" else [])
    if op == "fold-cap":
        tail = [ADD] if changed != "none" else []
        return [f"{v} c = e.Fn(e.Who, in a);", "if (c < cap)", "{", "    cap = c;", "    if (v > c)", "    {",
                "        v = c;"] + ["        " + t for t in tail] + ["    }", "}"]
    if op == "fold-set":
        if changed == "none":
            return ["v = e.Fn(e.Who, in a, v);"]
        test = {"ne": "prev != v", "int-ne": "(int)prev != (int)v",
                "trunc-ne": "decimal.Truncate(prev) != decimal.Truncate(v)"}[changed]
        return [f"{v} prev = v;", "v = e.Fn(e.Who, in a, v);", f"if ({test}) {ADD}"]
    if op == "try":
        if not s.value:
            return [f"if (e.Fn(e.Who, in a)) {ADD}"]
        if changed == "none":
            return ["e.Fn(e.Who, in a, v, out v);"]
        if "out-not-null" in p.get("also", []):
            return ["if (e.Fn(e.Who, in a, v, out var next) && next is { } got)", "{", "    v = got;", f"    {ADD}",
                    "}"]
        return ["if (e.Fn(e.Who, in a, v, out var next))", "{", "    v = next;", f"    {ADD}", "}"]
    if op == "predicate-all":
        return ["if (!e.Fn(e.Who, in a))", "{", "    preventer = e.Who;", "    return false;", "}"]
    if op == "predicate-any":
        return ["if (e.Fn(e.Who, in a))", "{", "    first = e.Who;", "    return true;", "}"]
    if op == "mutate":
        return ["e.Fn(e.Who, in a);"]
    raise GenError(f"{s.name}: unknown op {op}")


def _identity(s: Shape, in_passes: bool) -> list[str]:
    """The statements that end the dispatch with nothing changed."""
    if s.family == "value":
        return (["changed = Array.Empty<ListenerRef>();"] if s.tracks else []) + ["return v;"]
    if s.family == "try-in-place":
        return ["return Array.Empty<ListenerRef>();"]
    if s.family == "predicate-all":
        return ["preventer = null;", "return true;"]
    if s.family == "predicate-any":
        return ["first = null;", "return false;"]
    return ["return HookStatus.Done;"] if s.stops else ["return;"]


def _signature(s: Shape, passes: bool) -> str:
    name = s.name + ("Passes" if passes else "")
    params = [f"HookRuntime rt", f"in {s.name}Args a"]
    if s.family == "value":
        ret = s.vtype
        if passes:
            params.append(f"{s.vtype} v")
        if s.tracks:
            params.append("out IReadOnlyList<ListenerRef> changed")
    elif s.family == "try-in-place":
        ret = "IReadOnlyList<ListenerRef>"
    elif s.family == "predicate-all":
        ret = "bool"
        params.append("out ListenerRef? preventer")
    elif s.family == "predicate-any":
        ret = "bool"
        params.append("out ListenerRef? first")
    else:
        ret = "HookStatus" if s.stops else "void"
    return f"public static {ret} {name}({', '.join(params)})"


def _passes(s: Shape) -> list[str]:
    hooks = list(dict.fromkeys(p["hook"] for p in s.passes))
    any_ = " || ".join(f"rt.HasAny(HookId.{h})" for h in hooks)
    out = []
    if s.family == "value" and not s.split:
        out.append(f"{s.vtype} v = a.{pascal(s.value['name'])};")
    guard = f"cur is null && !({any_})" if s.stops else f"!({any_})"
    out += [f"if ({guard})", "{"] + ["    " + x for x in _identity(s, True)] + ["}"]
    if s.tracks or s.family == "try-in-place":
        out.append("List<ListenerRef>? ch = null;")
    waits = set(s.d["wait_all"])
    if waits:
        out.append("long mark = rt.HookActionMark();")
    it = ITER[s.d["iterator"]]
    for i, p in enumerate(s.passes):
        get = f"rt.Listeners<{_handler(s, p)}>(HookIterator.{it}, HookId.{p['hook']})"
        body = [f"// pass {i}: {p['hook']} ({p['op']}" + (f", changed {p['changed']}" if p["changed"] != "none" else "")
                + ")"]
        if s.stops:
            body += [f"if (from <= {i})", "{", f"    var l = cur ?? {get};", "    cur = null;"]
        else:
            body += ["{", f"    var l = {get};"]
        if p["op"] == "fold-cap":
            body.append(f"    {s.vtype} cap = {s.vtype}.MaxValue;")
        body += ["    while (l.Next(out var e))", "    {"]
        body += ["        " + x for x in _pass_body(s, i, p)]
        body += ["    }", "}"]
        if "when" in p:
            body = [f"if ({s.when(p['when'])})", "{"] + ["    " + x for x in body] + ["}"]
        out += body
        if i in waits:
            out.append(f"rt.WaitAll({disp_id(s.name)}, mark);")
    if s.family == "value":
        out += (["changed = HookRuntime.Changed(ch);"] if s.tracks else []) + ["return v;"]
    elif s.family == "try-in-place":
        out.append("return HookRuntime.Changed(ch);")
    elif s.family == "predicate-all":
        out += ["preventer = null;", "return true;"]
    elif s.family == "predicate-any":
        out += ["first = null;", "return false;"]
    elif s.stops:
        out.append("return HookStatus.Done;")
    return out


def _call_passes(s: Shape) -> str:
    if s.family == "value":
        return f"v = {s.name}Passes(rt, in a, v" + (", out changed);" if s.tracks else ");")
    if s.family == "predicate-all":
        return f"return {s.name}Passes(rt, in a, out preventer);"
    if s.family == "predicate-any":
        return f"return {s.name}Passes(rt, in a, out first);"
    if s.family == "try-in-place":
        return f"return {s.name}Passes(rt, in a);"
    if s.stops:
        return f"return {s.name}From(rt, in a, 0, null);"
    return f"{s.name}Passes(rt, in a);"


def _with_steps(s: Shape, shapes: dict[str, Shape]) -> list[str]:
    d = disp_id(s.name)
    out = []
    if s.family == "value":
        out.append(f"{s.vtype} v = a.{pascal(s.value['name'])};")
    called = False
    for st in s.d["pre"]:
        step = st["step"]
        if step == "netid-guard":
            line = [f"if (!Steps.NetIdGuard(rt, {d}))", "{"] + ["    " + x for x in _identity(s, False)] + ["}"]
        elif step == "negative-cost-passthrough":
            line = [f"if (!Steps.NegativeCostPassthrough(rt, {d}, v))", "{"] + [
                "    " + x for x in _identity(s, False)] + ["}"]
        elif step == "owner-in-combat":
            line = [f"if (!Steps.OwnerInCombat(rt, {d}, in a))", "{"] + ["    " + x for x in _identity(s, False)] + ["}"]
        elif step in ("enchant-add", "enchant-mul"):
            fn = "EnchantAdd" if step == "enchant-add" else "EnchantMul"
            line = [f"v = Steps.{fn}(rt, {d}, in a, v);"]
        elif step == "preview-hittable":
            if s.family != "value" or s.vtype != "decimal" or not s.tracks:
                raise GenError(f"{s.name}: preview-hittable needs a decimal fold with a changed set")
            line = [f"if (!Steps.PreviewHittable(rt, {d}, in a, v, {s.name}Passes, out v, out changed))",
                    "    " + _call_passes(s)]
            called = True
        else:
            raise GenError(f"{s.name}: unknown pre step {step!r}")
        if "when" in st:
            line = [f"if ({s.when(st['when'])})", "{"] + ["    " + x for x in line] + ["}"]
        out += line
    if not called:
        out.append(_call_passes(s))
    for st in s.d["post"]:
        step = st["step"]
        if step == "clamp-min0":
            out.append(f"v = Steps.ClampMin0({d}, v);")
        elif step.startswith("dispatch:"):
            other = shapes.get(step.split(":", 1)[1])
            if other is None or other.family != "value" or other.tracks:
                raise GenError(f"{s.name}: {step} is not a value dispatcher without a changed set")
            mine = {a["name"]: a for a in s.args}
            parts = []
            for a in other.args:
                if a.get("value"):
                    parts.append("v")
                elif a["name"] in mine:
                    parts.append(f"a.{pascal(a['name'])}")
                else:
                    raise GenError(f"{s.name}: {step}: no argument {a['name']}")
            out.append(f"v = {other.name}(rt, new {other.name}Args({', '.join(parts)}));")
        else:
            raise GenError(f"{s.name}: unknown post step {step!r}")
        if "when" in st:
            raise GenError(f"{s.name}: run-time flag on a post step")
    if s.family == "value":
        out.append("return v;")
    return out


def _summary(s: Shape) -> str:
    passes = "; ".join(f"{p['hook']} {p['op']}" + (f"/{p['changed']}" if p["changed"] != "none" else "")
                       + (f" also {','.join(p['also'])}" if p.get("also") else "")
                       + (f" when {p['when']}" if "when" in p else "") for p in s.passes)
    extra = []
    if s.d["context"] != "none":
        extra.append(f"context {s.d['context']}")
    if s.d["wait_all"]:
        extra.append(f"wait after {s.d['wait_all']}")
    if s.steps:
        extra.append("steps " + ", ".join(st["step"] for st in s.steps))
    if s.d["partner"]:
        extra.append("partner " + ", ".join(s.d["partner"]))
    return (f"game: Hook.{s.name}. {s.d['iterator']}: {passes}" + (". " + "; ".join(extra) if extra else "") + ".")


def _indent(lines: list[str], n: int) -> list[str]:
    return [(" " * n + x) if x else "" for x in lines]


def render(desc: dict) -> dict[str, str]:
    """The generated files, by path relative to src/Sts2Emulator."""
    ds = desc["dispatchers"]
    shapes = {n: Shape(n, ds[n]) for n in sorted(ds)}
    virtuals = sorted({p["hook"] for d in ds.values() for p in d["passes"]})
    ids = ["None = 0,", "", "// hook virtuals a dispatcher calls"] + [f"{h}," for h in virtuals] + [
        "", "// dispatchers (Hook's public static methods)"] + [f"Dispatch_{n}," for n in sorted(ds)]
    hook_id = (HEADER + "namespace Sts2Emulator.Core2;\n\n"
               "/// <summary>Hook virtuals and dispatchers of the game's Hook class, by name.</summary>\n"
               "public enum HookId : ushort\n{\n" + "\n".join(_indent(ids, 4)) + "\n}\n")
    body: list[str] = []
    for n, s in shapes.items():
        fields = ", ".join(f"{cs_type(a['type'], n)} {pascal(a['name'])}" for a in s.args)
        body += [f"/// <summary>Arguments of Hook.{n}.</summary>",
                 f"public readonly record struct {n}Args({fields});", ""]
    methods: list[str] = []
    decls: list[str] = []
    for n, s in shapes.items():
        for st in s.steps:
            if st["step"] in TYPED_STEPS:
                ret, fn, rest = TYPED_STEPS[st["step"]]
                decls += [f"/// <summary>{st['step']} of Hook.{n}.</summary>",
                          f"public static partial {ret} {fn}(HookRuntime rt, HookId dispatcher, in {n}Args a"
                          f"{rest.format(a=n + 'Args')});"]
        methods += [f"/// <summary>{_summary(s)}</summary>", _signature(s, False), "{"]
        if s.stops:
            cur = f"HookCursor<HookEvent<{n}Args>>"
            resume = ([f"var at = paused.At({disp_id(n)});"]
                      + ([f"{s.arg('ChoiceCtx')}.PopModel(at.Who);"] if s.d["context"] in PUSH else [])
                      + [f"return {n}From(rt, in a, at.Pass, ({cur})paused.Cursor!);"])
            methods += _indent(_with_steps(s, shapes) if s.split else [_call_passes(s)], 4) + [
                "}", "",
                f"/// <summary>Continues Hook.{n} from a pause it returned, once the paused listener's resume record "
                "has run to completion.</summary>",
                f"public static HookStatus {n}Resume(HookRuntime rt, in {n}Args a, in HookStatus paused)", "{"] + \
                _indent(resume, 4) + ["}", "",
                                      f"/// <summary>The passes of Hook.{n} from pass <c>from</c> (its cursor "
                                      "<c>cur</c> when resuming).</summary>",
                                      f"private static HookStatus {n}From(HookRuntime rt, in {n}Args a, int from, "
                                      f"{cur}? cur)", "{"]
            methods += _indent(_passes(s), 4) + ["}", ""]
            continue
        if s.split:
            methods += _indent(_with_steps(s, shapes), 4) + ["}", "",
                                                              f"/// <summary>The passes of Hook.{n}.</summary>",
                                                              _signature(s, True), "{"]
        methods += _indent(_passes(s), 4) + ["}", ""]
    hooks = (HEADER + "#nullable enable\nnamespace Sts2Emulator.Core2;\n\n" + "\n".join(body) +
             "/// <summary>One method per dispatcher of the game's Hook class.</summary>\n"
             "public static partial class Hooks\n{\n" + "\n".join(_indent(methods[:-1], 4)) + "\n}\n\n"
             "/// <summary>The named steps that read a dispatcher's arguments, typed by its argument record; "
             "Core2/Steps.cs implements each.</summary>\n"
             "public static partial class Steps\n{\n" + "\n".join(_indent(decls, 4)) + "\n}\n")
    return {HOOK_ID: hook_id, HOOKS: hooks}


def write(desc: dict, root: Path = ENGINE) -> None:
    for rel, text in render(desc).items():
        (root / rel).write_text(text, encoding="utf-8", newline="\n")


def stale(desc: dict, root: Path = ENGINE) -> list[str]:
    """The generated files that differ from a fresh generation (or are missing)."""
    out = []
    for rel, text in render(desc).items():
        p = root / rel
        if not p.exists():
            out.append(f"{rel}: missing")
        elif p.read_text(encoding="utf-8") != text:
            out.append(f"{rel}: stale (differs from a fresh generation from hooks.json)")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    desc = hx.load()
    if a.check:
        bad = stale(desc)
        for b in bad:
            print(b)
        return 1 if bad else 0
    write(desc)
    return 0


if __name__ == "__main__":
    sys.exit(main())
