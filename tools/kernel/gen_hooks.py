VALUE_OPS = {"fold-add", "fold-mul", "fold-cap", "fold-set", "try"}
EVENT_OPS = {"event", "filter-set", "preventer-only"}
NUMERIC = {"decimal", "int", "float"}
ALLOWED_CHANGED = {
    "event": {"none"}, "filter-set": {"none"}, "preventer-only": {"none"}, "mutate": {"none"},
    "predicate-all": {"none"}, "predicate-any": {"none"}, "fold-add": {"nonzero", "none"},
    "fold-mul": {"not-one", "none"}, "fold-cap": {"lowers", "none"}, "fold-set": {"ne", "int-ne", "trunc-ne", "none"},
    "try": {"try-true", "none"},
}


class GenError(Exception):
    pass


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


def cs_type(t: str, where: str) -> str:
    base, q = (t[:-1], "?") if t.endswith("?") else (t, "")
    if base not in KERNEL_TYPES:
        raise GenError(f"{where}: unknown kernel type {t!r}")
    return KERNEL_TYPES[base] + q


def disp_id(name: str) -> str:
    return f"HookId.Dispatch_{name}"


class Shape:
    """What the generator needs to know about one dispatcher, validated."""

    def __init__(self, name: str, d: dict):
        self.name, self.d = name, d
        if "args" not in d:
            raise GenError(f"{name}: no args")
        self.args = d["args"]
        for a in self.args:
            cs_type(a["type"], name)
        self.passes = d["passes"]
        ops = {p["op"] for p in self.passes}
        for p in self.passes:
            if p["op"] not in ALLOWED_CHANGED:
                raise GenError(f"{name}: unknown op {p['op']!r}")
            if p["changed"] not in ALLOWED_CHANGED[p["op"]]:
                raise GenError(f"{name}: {p['hook']}: op {p['op']} cannot track changed {p['changed']!r}")
        values = [a for a in self.args if a.get("value")]
        if len(values) > 1:
            raise GenError(f"{name}: more than one value argument")
        self.value = values[0] if values else None
        self.vtype = cs_type(self.value["type"], name) if self.value else None
        if ops <= EVENT_OPS:
            self.family = "event"
        elif ops == {"mutate"}:
            self.family = "mutate"
        elif ops == {"predicate-all"}:
            self.family = "predicate-all"
        elif ops == {"predicate-any"}:
            self.family = "predicate-any"
        elif ops == {"try"} and not self.value:
            self.family = "try-in-place"
        elif ops <= VALUE_OPS and self.value:
            self.family = "value"
            if ops & {"fold-add", "fold-mul", "fold-cap"} and self.vtype not in NUMERIC:
                raise GenError(f"{name}: arithmetic fold over {self.vtype}")
        else:
            raise GenError(f"{name}: ops {sorted(ops)} do not make one dispatcher shape")
        if self.family == "mutate" and not any(a["type"].rstrip("?") in MUTABLE for a in self.args):
            raise GenError(f"{name}: mutate dispatcher without a mutable argument (one of {', '.join(sorted(MUTABLE))})")
        for p in self.passes:
            also = p.get("also", [])
            if also and (p["op"] != "try" or not self.value or p["changed"] == "none"):
                raise GenError(f"{name}: {p['hook']}: condition parts on a pass that is not a tracked try over a value")
            for x in also:
                if x not in hx.ALSO:
                    raise GenError(f"{name}: {p['hook']}: unknown condition part {x!r}")
            if also and self.vtype.endswith("?"):
                raise GenError(f"{name}: {p['hook']}: out-not-null over a nullable value")
        self.tracks = any(p["changed"] != "none" for p in self.passes)
        self.steps = d["pre"] + d["post"]
        self.split = bool(self.steps)
        # Every event context but per-listener awaits each listener's whole task: the dispatch stops at a pause.
        self.stops = self.family == "event" and d["context"] != "per-listener"
        if self.stops and (d["wait_all"] or d["post"]):
            raise GenError(f"{name}: a dispatcher that stops at a pause cannot have wait points or post steps")
        if self.stops and d["context"] in PUSH and any(p["op"] != "event" for p in self.passes):
            raise GenError(f"{name}: a pushed context over a pass that does not push")

    def arg(self, type_: str) -> str:
        found = [a for a in self.args if a["type"].rstrip("?") == type_]
        if len(found) != 1:
            raise GenError(f"{self.name}: needs exactly one {type_} argument, has {len(found)}")
        return "a." + pascal(found[0]["name"])

    def when(self, flag: str) -> str:
        enum = flag.split(".")[0]
        return f"({self.arg(enum)} & {flag}) != 0"


