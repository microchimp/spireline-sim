"""Draw-pile stream sites for the fight solver (docs/rebuild/FIGHT_SOLVER.md section 4).

    python -m tools.solver.draw_sites build    # writes tools/solver/draw_sites.json from the engine source
    python -m tools.solver.draw_sites check    # the file equals a fresh build (exit 1 if not)

A draw-pile site is a line of the old engine that rolls on the Shuffle stream (``state.ShuffleRng``) or
shuffles the draw pile: the shuffles (the cards join the draw model's unknown middle, no roll), the random
placements (a uniform slot, no roll), the random picks from the pile (a chance node over its values), the
draws from the top, a pick from the hand or the discard on the Shuffle stream, the lines that only hand the
stream on to a callee whose own draw sites are classed (pass-through), and the rest, which the solver refuses
until each is classed. A line is classed by the statement it is part of (an argument line by its call). Each
entry names the file, the enclosing method and the anchor text (the stripped line), as the kernel's
``sites.json`` does for dispatch sites; identifiers only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "Sts2Emulator"
OUT = Path(__file__).with_name("draw_sites.json")
FILES = ["Core/CombatEngine.cs", "Core/CombatFactory.cs", "Core/Effects/CardEffects.cs", "Core/Effects/RelicEffects.cs"]
SITE = re.compile(r"ShuffleRng\s*\?\?|ShufflePile\(|AddCardToDrawPileRandomly\(|RemoveFromDrawPileAt\(0\)")
METHOD = re.compile(r"^\s{4}(?:(?:public|internal|private|protected|static|unsafe|async)\s+)+[\w<>\[\],.? ()]+?\s+(\w+)\s*(?:<[^>]*>)?\(")


# Callees a line hands the Shuffle stream to without rolling on it here: the damage path (a debuff that draws
# for Vicious, a death that answers the fight's death hooks) reaches the stream only through draw sites of
# its own, which this file lists.
PASS_THROUGH = ("AnswerDeathsHoldingTheFightOpen(", "ApplyEnemyDebuffToTarget(")


def kind(line: str, method: str, stmt: str = "") -> str:
    if "RemoveFromDrawPileAt(0)" in line:
        return "draw-top"
    if method == "AddCardToDiscardPileRandomly":
        return "discard-placement"
    if "RandomFromDrawPile" in method or "RandomDrawPile" in method:
        return "pick"
    if "ShufflePile(" in line or method in ("ShuffleDiscardIntoDraw", "ShuffleIfNecessary"):
        return "shuffle"
    if "AddCardToDrawPileRandomly" in line or method == "AddCardToDrawPileRandomly" or "placementRng" in line:
        return "placement"
    if "AddCardToDrawPileRandomly(" in stmt:
        return "placement"
    if method == "AutoPlayStampedeAttacks":
        # StampedePower: one uniform pick of an attack in hand (a chance node over the hand's attacks).
        return "hand-pick"
    if method == "AutoPlayAttacksFromDiscard":
        # A stable shuffle of the discard's eligible attacks, first n taken: n drawn without replacement.
        return "discard-pick"
    if method == "DrawRng" or any(c in stmt for c in PASS_THROUGH):
        return "pass-through"
    return "unclassed"


def build() -> dict:
    sites = []
    for rel in FILES:
        method = "?"
        stmt: list[str] = []
        for line in (SRC / rel).read_text(encoding="utf-8").splitlines():
            m = METHOD.match(line)
            if m:
                method = m.group(1)
            text = line.strip()
            if not text.startswith("//"):
                stmt.append(text)
            if not (text.startswith("//") or not SITE.search(line) or m):
                sites.append({"file": rel, "method": method, "anchor": text, "kind": kind(text, method, " ".join(stmt))})
            if text.endswith((";", "{", "}")):
                stmt = []
    return {
        "_about": "Generated by tools/solver/draw_sites.py from the engine source; do not edit. Lines that roll on the "
        "Shuffle stream or shuffle the draw pile, by file, method and anchor text, with how the draw model takes them "
        "(FIGHT_SOLVER.md section 4): shuffle (joins the unknown middle), placement (a uniform slot), discard-placement (the "
        "discard is a multiset), pick (a chance node over the pile's values), draw-top (the draw), hand-pick and discard-pick (a chance node over "
        "the hand's or the discard's values), pass-through (the stream handed to a callee whose own sites are listed), "
        "unclassed (refused).",
        "format": 1,
        "sites": sites,
    }


def main(argv: list[str] | None = None) -> int:
    cmd = (argv if argv is not None else sys.argv[1:] or ["check"])[0]
    text = json.dumps(build(), indent=1) + "\n"
    if cmd == "build":
        OUT.write_text(text, encoding="utf-8", newline="\n")
        return 0
    ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
    print("draw sites: up to date" if ok else "draw sites: tools/solver/draw_sites.json differs from a fresh build")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
