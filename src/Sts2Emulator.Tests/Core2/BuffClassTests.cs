    private static string Class(BuffId id)
    {
        var m = OldModelIdsFixture.Power(id);
        return m.Kind switch
        {
            PowerMapKind.Game => $"Power({OldModelIdsFixture.Name(m)})",
            PowerMapKind.Piece => $"Piece({OldModelIdsFixture.Name(m)})",
            _ => m.Kind.ToString(),
        };
    }

    [Fact]
    public void EveryBuffIdHasItsPinnedClass()
    {
        var ids = Enum.GetValues<BuffId>();
        var missing = ids.Where(b => !Table.ContainsKey(b.ToString())).Select(b => $"{b} (rule: {Class(b)})").ToList();
        Assert.True(missing.Count == 0, "BuffIds with no pinned class, add them to the table: " + string.Join(", ", missing));
        var stale = Table.Keys.Where(k => !ids.Any(b => b.ToString() == k)).ToList();
        Assert.True(stale.Count == 0, "table rows with no BuffId: " + string.Join(", ", stale));
        var wrong = ids.Where(b => Table[b.ToString()] != Class(b)).Select(b => $"{b}: table {Table[b.ToString()]}, rule {Class(b)}").ToList();
        Assert.True(wrong.Count == 0, "BuffIds whose class changed: " + string.Join("; ", wrong));
    }

    [Fact] // the review's two cases: a fold member is Folded, and nothing falls through to EngineOnly
    public void FoldMembersAreFoldedAndTheFallbackIsNotModelled()
    {
        Assert.Equal(PowerMapKind.Folded, OldModelIdsFixture.Power(BuffId.SetupStrikePower).Kind);
        Assert.Equal(PowerMapKind.NotModelled, OldModelIdsFixture.Power(BuffId.Metallicize).Kind);
        Assert.Equal(PowerMapKind.NotModelled, OldModelIdsFixture.Power((BuffId)(-1)).Kind); // a value no rule saw
        Assert.Equal(6, Table.Values.Count(v => v == "EngineOnly"));
    }

    private static class OldModelIdsFixture
    {
        public static PowerMapping Power(BuffId id) => ListenerOrderTests.Ids.Power(id);

        public static string? Name(PowerMapping m) => ListenerOrderTests.Ids.PowerName(m.ModelId);
    }
